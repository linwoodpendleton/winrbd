/*
 * wri_aes.c - AES-128/192/256 key schedule and single-block encrypt / decrypt (FIPS 197).
 *
 * Written from the FIPS 197 description of the cipher: the S-box, the round structure and the
 * key expansion. The four rotated lookup tables of the classic table-driven form are derived
 * from one table each (te0 for encryption, td0 for decryption) by byte rotation, which keeps the
 * read-only data at 2.5 KiB for iPXE.
 *
 * NOT constant time. Every round does secret-indexed table lookups, so the code leaks key and
 * data dependent timing through the cache (architecture doc 4.2). The project's threat model is
 * test networks; a host that needs more provides its own AES through wr_prim_ops.
 *
 * Decryption is the "equivalent inverse cipher" whose middle round keys are InvMixColumns of the
 * encryption round keys. The context holds only the encryption schedule (wri_aes_ctx has room for
 * one), so the inverse mix of each middle round key is computed on the fly while decrypting.
 * That costs roughly a second table pass per round; it is acceptable because cephx messages are
 * small and the bulk path of secure mode (GCM) only uses the encrypt direction.
 *
 * No heap, no globals (the tables are const), no recursion. The context lives on the caller's
 * stack or arena. Block functions on a context that never passed wri_aes_setkey (rounds not 10,
 * 12 or 14), including one whose last wri_aes_setkey call failed, write 16 zero bytes instead of
 * garbage derived from uninitialised round keys. The context holds the secret key schedule: the
 * caller wipes it (wri_secure_zero) when done.
 */
#include "wri_aes.h"

