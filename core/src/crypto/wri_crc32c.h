/*
 * wri_crc32c.h - CRC-32C (Castagnoli, polynomial 0x1EDC6F41, reflected 0x82F63B78).
 *
 * RAW update: the caller supplies the running value, no initial or final inversion is applied
 * (msgr2.md 2.5). msgr2 uses seed 0 for the frame preamble and seed 0xFFFFFFFF for every
 * segment (including the revision-1 inline segment-0 CRC). Known answers over "123456789":
 * raw(seed 0xFFFFFFFF) = 0x1CF96D7C, raw(seed 0) = 0x58E3FA20; the textbook inversion-wrapped
 * CRC-32C of that string, 0xE3069283, is raw(0xFFFFFFFF) XOR 0xFFFFFFFF.
 * The tables are const arrays generated by core/tools/gen_crc32c_tab.py and committed
 * (wri_crc32c_tab.inc): no run-time table build, so no writable global.
 * Contract: p may be NULL only when n == 0 (the seed is returned); any alignment is fine; the call
 * is reentrant and does O(n) work with no cap, so a caller with a work budget feeds it in chunks
 * (the result chains: crc(crc(s, a), b) == crc(s, a || b)).
 */
#ifndef WRI_CRC32C_H
#define WRI_CRC32C_H

#include "wr_port.h"

uint32_t wri_crc32c(uint32_t crc, const uint8_t *p, size_t n);

#endif /* WRI_CRC32C_H */
