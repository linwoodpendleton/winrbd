"""Generate core/src/crypto/wri_crc32c_tab.inc, the const CRC-32C slicing tables.

Reflected polynomial 0x82F63B78 (Castagnoli). Row 0 is the byte-at-a-time table: for index i,
start with i and eight times shift right one bit, XOR-ing the polynomial when the bit shifted
out was 1. Row k (k >= 1) is row k-1 advanced by one further zero byte:
    T[k][i] = (T[k-1][i] >> 8) ^ T[0][T[k-1][i] & 0xFF]
so rows 0..3 serve slice-by-4 and rows 0..7 serve slice-by-8. The file is the body of a
braced initialiser `uint32_t tab[WRI_CRC32C_SLICE][256]`; rows past the configured slice
count are removed by the preprocessor.

Usage:
    gen_crc32c_tab.py             rewrite the committed file
    gen_crc32c_tab.py --check     exit 1 if the committed file differs from the generated text
    gen_crc32c_tab.py --out PATH  write somewhere else (with --check: compare that file)

Python 3 standard library only; the output is deterministic.
"""
import os
import sys

POLY = 0x82F63B78
ROWS = 8
PER_LINE = 8
DEFAULT_OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                           "..", "src", "crypto", "wri_crc32c_tab.inc")


def build_tables():
    t0 = []
    for i in range(256):
        c = i
        for _ in range(8):
            c = (c >> 1) ^ POLY if c & 1 else c >> 1
        t0.append(c)
    rows = [t0]
    for _ in range(1, ROWS):
        prev = rows[-1]
        rows.append([(v >> 8) ^ t0[v & 0xFF] for v in prev])
    return rows


def render(rows):
    out = []
    out.append("/* SPDX-License-Identifier: MIT */")
    out.append("/*")
    out.append(" * wri_crc32c_tab.inc - CRC-32C slicing tables (reflected polynomial 0x82F63B78).")
    out.append(" * GENERATED by core/tools/gen_crc32c_tab.py; do not edit. Body of the initialiser")
    out.append(" *     static const uint32_t tab[WRI_CRC32C_SLICE][256] = { #include this file };")
    out.append(" * Row 0 is the byte-wise table; rows 1..3 are added for slice-by-4, rows 4..7 for slice-by-8.")
    out.append(" */")
    for k, row in enumerate(rows):
        if k == 1:
            out.append("#if WRI_CRC32C_SLICE >= 4")
        if k == 4:
            out.append("#if WRI_CRC32C_SLICE >= 8")
        out.append("{ /* row %d */" % k)
        for j in range(0, 256, PER_LINE):
            chunk = ", ".join("0x%08Xu" % v for v in row[j:j + PER_LINE])
            out.append("\t" + chunk + ",")
        out.append("},")
        if k == 3 or k == 7:
            out.append("#endif")
    return "\n".join(out) + "\n"


def main(argv):
    check = False
    path = DEFAULT_OUT
    i = 1
    while i < len(argv):
        a = argv[i]
        if a == "--check":
            check = True
        elif a == "--out" and i + 1 < len(argv):
            i += 1
            path = argv[i]
        else:
            sys.stderr.write("usage: gen_crc32c_tab.py [--check] [--out PATH]\n")
            return 2
        i += 1
    text = render(build_tables())
    path = os.path.normpath(path)
    if check:
        try:
            with open(path, "r", newline="") as f:
                have = f.read()
        except OSError as e:
            sys.stderr.write("gen_crc32c_tab: cannot read %s: %s\n" % (path, e))
            return 1
        if have != text:
            sys.stderr.write("gen_crc32c_tab: %s is out of date; run core/tools/gen_crc32c_tab.py\n" % path)
            return 1
        return 0
    with open(path, "w", newline="") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
