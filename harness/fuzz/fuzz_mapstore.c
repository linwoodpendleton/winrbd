static void check(int cond)
{
	if (!cond)
		abort();
}

/* A region of `n` bytes (16-aligned) between two guards. */
typedef struct greg {
	uint8_t *raw, *p;
	size_t n;
} greg;

static void greg_new(greg *g, size_t n)
{
	g->raw = (uint8_t *)malloc(n + 2u * GUARD);
	check(g->raw != NULL);
	memset(g->raw, PAT, n + 2u * GUARD);
	g->p = g->raw + GUARD;
	memset(g->p, 0, n);
	g->n = n;
}

static int greg_ok(const greg *g)
{
	size_t i;

	for (i = 0; i < GUARD; i++)
		if (g->raw[i] != PAT || g->raw[GUARD + g->n + i] != PAT)
			return 0;
	return 1;
}

static int status_ok(wr_status st)
{
	return st == WR_OK || st == WR_E_MAP_NONE || st == WR_E_POOL_NOT_FOUND || st == WR_E_POOL_UNSUPPORTED || st == WR_E_PLACE_UNMAPPABLE ||
	       st == WR_E_RANGE || st == WR_E_CRUSH_NO_RULE || st == WR_E_CRUSH_UNSUPPORTED || st == WR_E_CRUSH_LOOP || st == WR_E_CRUSH_WORK ||
	       st == WR_E_TOOBIG || st == WR_E_INVAL;
}

static void queries(ms_fix *f)
{
	uint32_t h, seed;
	wr_target t;
	wri_oid oid;
	const wri_map_pool *p;

	memset(&oid, 0, sizeof(oid));
	oid.name = (const uint8_t *)"rbd_data.fuzz.0000000000000001";
	oid.name_len = 30;
	for (h = 0; h < 10; h++) {
		wr_status st = wri_mapstore_pool(&f->s, h, &p);

		check(status_ok(st));
		if (st == WR_OK)
			check(p != NULL && p->present);
		for (seed = 0; seed < 3; seed++) {
			st = wri_mapstore_target_pg(&f->s, h, seed, &t);
			check(status_ok(st));
			if (st == WR_OK)
				check(t.n_acting > 0 && t.n_acting <= WR_MAP_REP_MAX && t.acting_primary >= 0 && t.epoch == f->s.epoch);
			else if (st != WR_E_PLACE_UNMAPPABLE)
				check(t.n_acting == 0 && t.acting_primary == -1);
		}
		st = wri_mapstore_target(&f->s, h, &oid, &t);
		check(status_ok(st));
		if (st == WR_OK)
			check(t.n_acting > 0 && t.acting_primary >= 0);
	}
}

