/*
 * Fuzz target for the map store (core/src/osdmap/wri_mapstore.c, wri_mapstore_msg.c; docs/design/core-architecture.md 15.5).
 *
 * The held map is fixed: the lab's full map of epoch 42 (harness/vectors/osdmap/full-e42.hex, 3,156 bytes, compiled in below).
 * The input is one byte of mode followed by the front of one MOSDMap message, which a scripted source (mapstore_rig.h) hands
 * to the store as an exact-size heap copy that is freed when the store releases it. Mode bits: 0 start with the base map held
 * (else with no map), 1 put the base map's fsid into the front (so the entries get past the fsid gate), 2 and 3 the message
 * header version (4, 2, 1, 3), 4 CRC checking off (so that mutations reach the row parsers), 5 post the front a second time,
 * 6 track eight names (one twice, one empty) instead of the two the lab has, 7 track one more name after the base map is held
 * (the late track: the held map has no record of it, and a full map of the held epoch is the one that resolves it). The store is stepped, with the clock moving, until
 * it reports no more work. Properties (a violated one aborts):
 *
 *   - the held epoch never decreases and the held fsid never changes; an epoch that moves by more than one in a step moved by a
 *     full map (an incremental is applied only to epoch - 1: no incremental across a gap);
 *   - every failed step (a failure counted in fail_streak) leaves a full-map request pending or sent, or the store fatal; after
 *     a step at a far later time no request is pending unless the store is fatal;
 *   - a fatal store raised WR_EV_FATAL exactly once, had no map, and asks for nothing afterwards;
 *   - the held map passes wri_osdmap_check after every step, its bytes are inside the slot, and a map that was held and is
 *     not replaced is byte for byte what it was;
 *   - nothing is written outside the two slots or the cache (guard bytes), nothing reads a front after its release (the front
 *     is freed at release: ASan), a release never happens with nothing held, and when the store reports no more work every
 *     message has been released;
 *   - the store's own counters add up: requests = WR_EV_MAP_RESYNC events, epochs adopted = WR_EV_MAP events, and every
 *     placement query on the held map answers with a status of the documented set and a usable target when it says OK.
 *
 * Seeds (harness/fuzz/seeds/fuzz_mapstore): the mode byte and a front assembled from the lab vectors (the real full map of epoch
 * 42, the real incrementals 43 and up, cut, flipped, gapped, with another fsid, in lists of other shapes) and hostile counts.
 */
