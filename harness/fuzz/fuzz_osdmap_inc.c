/* Touch everything a placement could reach and check the facts that make the accessors safe. */
static void walk(const wri_osdmap *m)
{
	uint32_t i, k, j;
	volatile uint64_t sink = 0;

	check(m->magic == WRI_MAP_MAGIC && m->bytes <= m->cap && m->bytes >= sizeof(*m));
	for (i = 0; i < m->max_osd; i++) {
		const wri_osd_addr *a = &wri_map_addr(m)[i];

		sink += wri_map_state(m)[i] + wri_map_weight(m)[i] + wri_osd_aff(m, (int32_t)i) + a->port + a->nonce;
		check(a->family == 0 || a->family == WR_AF_IPV4 || a->family == WR_AF_IPV6);
		check(wri_osd_up(m, (int32_t)i) <= wri_osd_exists(m, (int32_t)i));
	}
	for (k = 0; k < m->n_pools; k++) {
		const wri_map_pool *p = &wri_map_pools(m)[k];

		check(p->present <= 1u);
		if (p->present == 0)
			continue;
		check(p->status == WR_OK || p->status == WR_E_POOL_UNSUPPORTED || p->status == WR_E_CRUSH_NO_RULE ||
		      p->status == WR_E_CRUSH_UNSUPPORTED || p->status == WR_E_CRUSH_LOOP || p->status == WR_E_CRUSH_ENCODING ||
		      p->status == WR_E_CRUSH_WORK);
		if (p->status == WR_OK) {
			check(p->type == WRI_POOL_REPLICATED && p->size >= 1 && p->size <= WRI_REP_MAX && p->pg_num > 0 && p->pgp_num > 0);
			check((p->pg_num_mask & (p->pg_num_mask + 1u)) == 0 && (p->pgp_num_mask & (p->pgp_num_mask + 1u)) == 0);
		}
	}
	for (k = 0; k < WRI_TAB_COUNT; k++) {
		const uint64_t *keys = m->tab[k].n != 0 ? wri_pgtab_keys(m, k) : NULL;
		const uint32_t *offs = wri_pgtab_offs(m, k);
		const int32_t *vals = wri_pgtab_vals(m, k);

		for (i = 0; i < m->tab[k].n; i++) {
			const int32_t *got;
			uint32_t n;

			check(wri_pgtab_find(m, k, keys[i], &got, &n));
			check(n == offs[i + 1u] - offs[i] && got == vals + offs[i]);
			for (j = 0; j < n; j++)
				sink += (uint32_t)got[j];
			check((keys[i] >> 32) < ((uint64_t)1 << 31)); /* only tracked pools, whose ids fit 31 bits */
		}
	}
	check(wri_map_crush(m) != NULL);
	(void)sink;
}

static int allowed(wr_status st)
{
	return st == WR_E_MAP_VERSION || st == WR_E_MAP_CORRUPT || st == WR_E_MAP_CRC || st == WR_E_MAP_BUDGET || st == WR_E_MAP_FSID ||
	       st == WR_E_MAP_EPOCH || st == WR_E_MAP_RESYNC || st == WR_E_CRUSH_ENCODING || st == WR_E_CRUSH_UNSUPPORTED;
}

/* One apply with all the checks; returns the status. `held` is the map applied to, which must not change. */
static wr_status one(const wri_mapcfg *cfg, const wri_osdmap *held, const uint8_t *blob, size_t n, room *r, wr_errinfo *why)
{
	uint8_t *keep = (uint8_t *)malloc(held->bytes);
	wr_status st;

	if (keep == NULL)
		abort();
	memcpy(keep, held, held->bytes);
	memset(why, 0, sizeof(*why));
	st = wri_osdmap_apply_inc(cfg, held, blob, n, r->p, r->cap, why);
	room_guards(r);
	check(memcmp(keep, held, held->bytes) == 0); /* the held map is never written */
	free(keep);
	if (st == WR_OK) {
		const wri_osdmap *m = (const wri_osdmap *)(const void *)r->p;

		check(wri_osdmap_check(m) == WR_OK);
		walk(m);
	} else {
		uint32_t magic;

		check(allowed(st));
		check(why->status == st && why->module != 0 && why->what != NULL);
		memcpy(&magic, r->p, 4);
		check(magic == 0);
	}
	return st;
}

/* The two pre-fills, the exact size and one byte less. */
static wr_status both(const wri_mapcfg *cfg, const wri_osdmap *held, const uint8_t *blob, size_t n, room *ra, room *rb)
{
	wr_errinfo why = { 0 };
	wr_status sa, sb;

	room_fill(ra, PAT_A);
	sa = one(cfg, held, blob, n, ra, &why);
	room_fill(rb, PAT_B);
	sb = one(cfg, held, blob, n, rb, &why);
	check(sa == sb);
	if (sa == WR_OK) {
		const wri_osdmap *ma = (const wri_osdmap *)(const void *)ra->p;
		const wri_osdmap *mb = (const wri_osdmap *)(const void *)rb->p;
		wri_map_blob_info bi;
		room rx;
		wri_mapcfg c2 = *cfg;
		size_t used = ma->bytes;

		check(ma->bytes == mb->bytes);
		check(memcmp(ra->p, rb->p, used) == 0);
		check(wri_osdmap_inc_info(blob, n, &bi, &why) == WR_OK);
		check(bi.epoch == ma->epoch && memcmp(bi.fsid, ma->fsid, 16) == 0);
		if (bi.has_fullmap == 0) { /* a plain incremental is not the next one a second time */
			room r2;
			wr_status s2;

			room_new(&r2, ra->cap);
			room_fill(&r2, PAT_B);
			s2 = wri_osdmap_apply_inc(cfg, ma, blob, n, r2.p, r2.cap, &why);
			room_guards(&r2);
			check(s2 == WR_E_MAP_EPOCH);
			free(r2.buf);
		}

		/* the exact size gives the same map (its `cap` is the one field that differs), one byte less is a budget failure */
		room_new(&rx, used);
		c2.slot_bytes = (uint32_t)used;
		room_fill(&rx, PAT_B);
		check(one(&c2, held, blob, n, &rx, &why) == WR_OK);
		check(memcmp(rx.p, ra->p, 8) == 0 && memcmp(rx.p + 12, ra->p + 12, used - 12u) == 0);
		free(rx.buf);
		room_new(&rx, used - 1u);
		c2.slot_bytes = (uint32_t)(used - 1u);
		room_fill(&rx, PAT_A);
		check(one(&c2, held, blob, n, &rx, &why) == WR_E_MAP_BUDGET);
		free(rx.buf);
	}
	return sa;
}

int LLVMFuzzerTestOneInput(const uint8_t *data, size_t size)
{
	uint8_t *blob = (uint8_t *)malloc(size ? size : 1u);
	uint8_t *fixed = (uint8_t *)malloc(size ? size : 1u);
	uint8_t *cut = (uint8_t *)malloc(size ? size : 1u);
	room ra, rb, hold, hold2;
	wri_mapcfg cfg, alt;
	wri_map_blob_info bi;
	wr_errinfo why = { 0 };
	wr_status first;

	if (blob == NULL || fixed == NULL || cut == NULL)
		abort();
	room_new(&ra, ROOM);
	room_new(&rb, ROOM);
	room_new(&hold, ROOM);
	room_new(&hold2, ROOM);
	if (size != 0) {
		memcpy(blob, data, size);
		memcpy(fixed, data, size);
		memcpy(cut, data, size);
	}

	/* the held maps: the lab's epoch 42 decoded with the two sets of tracked names */
	mkcfg(&cfg, ROOM, 0);
	mkcfg_alt(&alt, ROOM);
	room_fill(&hold, PAT_A);
	room_fill(&hold2, PAT_A);
	check(wri_osdmap_decode_full(&cfg, BASE, sizeof(BASE), hold.p, hold.cap, &why) == WR_OK);
	check(wri_osdmap_decode_full(&alt, BASE, sizeof(BASE), hold2.p, hold2.cap, &why) == WR_OK);

	first = both(&cfg, (const wri_osdmap *)(const void *)hold.p, blob, size, &ra, &rb);

	/* the CRC recomputed over the mutated bytes (when the envelopes nest), checked this time */
	mkcfg(&cfg, ROOM, 1);
	if (size >= 12 && wrt_mg_fix_crc(fixed, size, 1) == 0)
		(void)both(&cfg, (const wri_osdmap *)(const void *)hold.p, fixed, size, &ra, &rb);
	else
		(void)both(&cfg, (const wri_osdmap *)(const void *)hold.p, blob, size, &ra, &rb); /* whatever it is, the check must not crash */

	/* the other tracked-name set (duplicates, an empty name, eight pools) and a small max_osd limit */
	(void)both(&alt, (const wri_osdmap *)(const void *)hold2.p, blob, size, &ra, &rb);

	/* a slot that holds the map or not: success or budget, the same rules */
	mkcfg(&cfg, 2048u, 0);
	{
		room rs;

		room_new(&rs, 2048u);
		room_fill(&rs, PAT_A);
		(void)one(&cfg, (const wri_osdmap *)(const void *)hold.p, blob, size, &rs, &why);
		free(rs.buf);
	}

	/* the header facts of whatever this is: never a crash, outputs zeroed on failure */
	if (wri_osdmap_inc_info(blob, size, &bi, &why) != WR_OK) {
		wri_map_blob_info z;

		memset(&z, 0, sizeof(z));
		check(memcmp(&bi, &z, sizeof(z)) == 0);
	}

	if (first == WR_OK && size > 0) { /* an incremental that applies, cut by one byte: the wrapper claims more than there is */
		mkcfg(&cfg, ROOM, 0);
		room_fill(&ra, PAT_A);
		check(one(&cfg, (const wri_osdmap *)(const void *)hold.p, cut, size - 1u, &ra, &why) != WR_OK);
	}
	free(blob);
	free(fixed);
	free(cut);
	free(ra.buf);
	free(rb.buf);
	free(hold.buf);
	free(hold2.buf);
	return 0;
}
