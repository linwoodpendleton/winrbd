/*
 * Fuzz target for applying an OSDMap::Incremental (core/src/osdmap/wri_osdmap_inc.c, wri_osdmap_inc2.c).
 *
 * The held map is fixed: the lab's full map of epoch 42 (harness/vectors/osdmap/full-e42.hex, 3,156 bytes, three OSDs, pools .mgr and
 * winrbd), compiled in below and decoded at the start of every input. The whole input is one incremental (an exact-size heap copy,
 * so ASan sees any over-read). It is applied twice, into a slot pre-filled with one byte and a slot pre-filled with another, with
 * four tracked pool names and the CRC check off (so that mutations reach the row parsers), once more with the CRC recomputed (so a
 * mutated incremental gets past the check when the envelopes still nest), once with a second set of eight names (one twice, one
 * empty, names the lab does not have) and max_osd limited to 16, and once into a slot too small for most results. Properties (a
 * violated one traps):
 *
 *   - a failure is one of the map or CRUSH statuses, with the same status, a module and a reason in the errinfo, and the new slot has
 *     magic 0; a success gives a map that passes wri_osdmap_check, whose bytes are inside the slot, whose guards are intact, and whose
 *     per-OSD arrays, pool records and tables can all be walked through the accessors;
 *   - the held map is byte for byte what it was after every apply (it is never written);
 *   - the two pre-fills give the same status and the same bytes (a decision taken on a byte of the slot that the decoder did not
 *     write shows up as a difference);
 *   - a slot of exactly the used size gives the same map, one byte less gives WR_E_MAP_BUDGET;
 *   - wri_osdmap_inc_info agrees with a successful apply on the epoch and the fsid, and never reads past the input;
 *   - a plain (not embedded) incremental that applied does not apply a second time to the map it produced (its epoch is no longer
 *     the next one: WR_E_MAP_EPOCH);
 *   - the input cut by one byte is refused (the wrapper claims more than there is).
 */
