static void check(int cond)
{
	if (!cond)
		__builtin_trap();
}

typedef struct room {
	uint8_t *buf; /* GUARD + cap + GUARD bytes, malloc alignment */
	uint8_t *p;   /* 16-byte aligned start of the slot inside buf */
	size_t cap;
	uint8_t pat;
} room;

static void room_new(room *r, size_t cap)
{
	uintptr_t a;

	r->cap = cap;
	r->buf = (uint8_t *)malloc(cap + 2u * GUARD + 16u);
	if (r->buf == NULL)
		abort();
	a = ((uintptr_t)r->buf + GUARD + 15u) & ~(uintptr_t)15u;
	r->p = (uint8_t *)a;
}

static size_t room_total(const room *r) { return (size_t)(r->p - r->buf) + r->cap + GUARD; }

static void room_fill(room *r, uint8_t pat)
{
	r->pat = pat;
	memset(r->buf, pat, room_total(r));
}

static void room_guards(const room *r)
{
	size_t i, pre = (size_t)(r->p - r->buf);

	for (i = 0; i < pre; i++)
		check(r->buf[i] == r->pat);
	for (i = pre + r->cap; i < room_total(r); i++)
		check(r->buf[i] == r->pat);
}

static void mkcfg(wri_mapcfg *c, uint32_t slot_bytes, int verify)
{
	static const char *const names[] = {".mgr", "winrbd", "pool1", "pool2"};
	unsigned k;

	memset(c, 0, sizeof(*c));
	c->slot_bytes = slot_bytes;
	c->max_osd = 4096;
	c->work_max = 200000;
	c->verify_crc = (uint8_t)verify;
	c->n_pools = 4;
	for (k = 0; k < 4; k++) {
		c->name_len[k] = (uint8_t)strlen(names[k]);
		memcpy(c->name[k], names[k], c->name_len[k]);
	}
}

